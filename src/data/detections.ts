// Helper function to generate polygon bounding box around center coordinates
function createBoundingPolygon(center: [number, number], offsetHa = 0.005): [number, number][] {
  const [lat, lng] = center;
  return [
    [Number((lat + offsetHa).toFixed(4)), Number((lng - offsetHa).toFixed(4))],
    [Number((lat + offsetHa).toFixed(4)), Number((lng + offsetHa).toFixed(4))],
    [Number((lat - offsetHa).toFixed(4)), Number((lng + offsetHa).toFixed(4))],
    [Number((lat - offsetHa).toFixed(4)), Number((lng - offsetHa).toFixed(4))]
  ];
}

