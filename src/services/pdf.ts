import jsPDF from 'jspdf';
import { DetectionSector } from '@/types';
import { TOPICS } from '@/data/topics';

export const generatePdfReport = (sector: DetectionSector) => {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const topic = TOPICS[sector.category];

  // Header Banner
  doc.setFillColor(15, 23, 42); // slate-900
  doc.rect(0, 0, 210, 28, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.text('GeoFind AI — Satellite Intelligence Report', 14, 14);

  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.text('Tamil Nadu Land-Use & Change Detection Intelligence Platform', 14, 20);

  doc.setFontSize(8);
  doc.text(`Ref ID: GEOFIND-TN-${sector.id.toUpperCase()}`, 155, 14);
  doc.text(`Generated: ${new Date().toISOString().split('T')[0]}`, 155, 20);

  // Status Badge
  doc.setFillColor(239, 68, 68);
  if (sector.category === 'deforestation') doc.setFillColor(34, 197, 94);
  if (sector.category === 'construction') doc.setFillColor(249, 115, 22);
  if (sector.category === 'sandmining') doc.setFillColor(59, 130, 246);
  if (sector.category === 'wetland') doc.setFillColor(168, 85, 247);

  doc.rect(14, 34, 182, 10, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.text(`DETECTION CATEGORY: ${topic?.name.toUpperCase()} (CONFIDENCE: ${sector.confidence}% - DEMO)`, 18, 41);

  // Location & Summary Table
  doc.setTextColor(15, 23, 42);
  doc.setFontSize(12);
  doc.setFont('helvetica', 'bold');
  doc.text('1. Location & Change Overview', 14, 53);

  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');

  const details = [
    ['District Location:', `${sector.district} District, Tamil Nadu`],
    ['Specific Sector:', sector.locationName],
    ['Center Coordinates:', `${sector.center[0].toFixed(4)}° N, ${sector.center[1].toFixed(4)}° E`],
    ['Total Affected Area:', `${sector.areaHa} Hectares`],
    ['Baseline Acquisition Date:', sector.acquisitionDates.before],
    ['Post-Change Acquisition Date:', sector.acquisitionDates.after],
    ['Change Classification:', sector.changeType],
    ['Primary Satellite Sensor:', sector.sensor],
  ];

  let yPos = 60;
  details.forEach(([label, val]) => {
    doc.setFont('helvetica', 'bold');
    doc.text(label, 16, yPos);
    doc.setFont('helvetica', 'normal');
    doc.text(val, 75, yPos);
    yPos += 6;
  });

  // Description Section
  yPos += 4;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.text('2. Spectral & Spatial Findings', 14, yPos);

  yPos += 6;
  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.text(sector.description, 16, yPos, { maxWidth: 178 });

  // Legal & Verification Footer
  yPos += 24;
  doc.setLineWidth(0.5);
  doc.setDrawColor(226, 232, 240);
  doc.line(14, yPos, 196, yPos);

  yPos += 8;
  doc.setFontSize(8);
  doc.setTextColor(100, 116, 139);
  doc.text('Official document automatically generated by GeoFind AI Engine for Tamil Nadu State Administration.', 14, yPos);
  doc.text('Data Source: Copernicus Sentinel-2 MSI 10m L2A | Spatial Co-registration RMSE < 0.15px', 14, yPos + 4);

  doc.save(`GeoFind_Report_${sector.district}_${sector.category}.pdf`);
};
